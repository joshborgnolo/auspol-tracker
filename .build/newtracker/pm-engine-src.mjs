/* The browser's copy of the primary model's filter and smoother: the Primary
   tab's pollster menu (pv-agg.js) re-runs the model on the ticked houses at
   the build's settings. Generated from primary-model.mjs – the named
   top-level declarations, "export" dropped, in one IIFE that sets
   window.AP.pmEngine – so the two can't drift. build.mjs writes
   assets/pm-engine.js from it and ships it in the pv-agg module;
   test-pv-recompute.mjs checks the committed file is current. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const NEED = ["DEFF", "WIDE_SD", "PARTIES", "helmert", "cholIn", "cholSolveVec", "categoriesOf", "stepOf", "zeroBasis",
  "makeLayout", "predictStep", "LOG2PI", "runFilter", "smooth", "softmaxAlr", "alrOf", "prepare"];
export function makeEngineSource() {
  const src = fs.readFileSync(path.join(HERE, "primary-model.mjs"), "utf8").split("\n");
  /* top-level chunks: a declaration at column 0 runs to the next one */
  const starts = [];
  src.forEach((l, i) => { const m = l.match(/^(?:export )?(?:function\*? |const |let )([A-Za-z0-9_$]+)/); if (m) starts.push({ i, name: m[1] }); });
  const chunks = new Map();
  starts.forEach((s, j) => {
    let end = j + 1 < starts.length ? starts[j + 1].i : src.length;
    /* stop before a comment block that introduces the next declaration */
    while (end > s.i + 1 && /^\s*(\/\*|\*|$|\/\/)/.test(src[end - 1]) && !/\*\/\s*$/.test(src[end - 1]) ) end--;
    let e2 = end; while (e2 > s.i + 1 && src[e2 - 1].trim() === "") e2--;
    chunks.set(s.name, src.slice(s.i, end).join("\n").replace(/^export /, ""));
  });
  const missing = NEED.filter((n) => !chunks.has(n));
  if (missing.length) throw new Error("pm-engine: primary-model.mjs lacks " + missing.join(", "));
  const body = NEED.map((n) => chunks.get(n)).join("\n");
  return `/* GENERATED by .build/newtracker/pm-engine-src.mjs from primary-model.mjs – do not edit.
   The primary model's filter and smoother for the Primary tab's pollster menu. */
(() => {
  "use strict";
${body}
  window.AP = window.AP || {};
  window.AP.pmEngine = { prepare, runFilter, smooth, softmaxAlr, alrOf, makeLayout, PARTIES, DEFF };
})();
`;
}
if (process.argv[1] && path.basename(process.argv[1]) === "pm-engine-src.mjs") {
  fs.writeFileSync(path.join(HERE, "assets", "pm-engine.js"), makeEngineSource());
  console.log("wrote assets/pm-engine.js");
}
