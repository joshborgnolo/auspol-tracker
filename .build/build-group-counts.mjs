/* build-group-counts.mjs – data/group-counts.json: the AEC's House first
   preferences at each election 1993–2025, nationally, by state group and (from
   1996) by AEC seat type, summed from map/data/core-<year>.json's state
   totals and divisions (each division's own classification that year). The
   vote-by-group model (gen-data §7gm) reads each group's result against the
   nation's as the count of its gap on polling day. 2025 is checked against
   the charts' own rings (gen-data DEMO_STATE_ELECTION / DEMO_LOC_ELECTION),
   which gen-data uses for 2025 itself: Outer metro differs by up to 0.24
   (a division classed differently there), reported, not failed.
     node .build/build-group-counts.mjs */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const YEARS = [1993,1996,1998,2001,2004,2007,2010,2013,2016,2019,2022,2025];
const KEYS = ['alp','lnp','onp','grn','oth'];
const zero = () => [0,0,0,0,0];
const fromPrim = p => [p.alp||0, p.lnp||0, p.onp||0, p.grn||0, (p.oth||0)+(p.ind||0)];
const add = (a,b) => a.map((x,i)=>x+b[i]);
const fin = v => { const f=v.reduce((a,b)=>a+b,0); return { pct: v.map(x=>+(100*x/f).toFixed(2)), votes: v, formal: f }; };
const BUCKET = { alp:0, lnp:1, onp:2, grn:3, ind:4, oth:4 };
const CLS = { 'Inner Metropolitan':'Inner metro','Outer Metropolitan':'Outer metro','Provincial':'Provincial','Rural':'Rural' };
const fails = [], out = { _about: 'Generated by .build/build-group-counts.mjs from map/data/core-*.json; shares of formal first preferences, oth includes independents', keys: KEYS, elections: {} };
const polls = JSON.parse(fs.readFileSync(path.join(root,'data/polls.json'),'utf8')).elections || {};
for (const y of YEARS) {
  const d = JSON.parse(fs.readFileSync(path.join(root,`map/data/core-${y}.json`),'utf8'));
  const A = s => fromPrim(d.agg[s].prim);
  const sum = (...s) => s.map(A).reduce(add, zero());
  const e = { date: d.date, Nat: fin(A('AUS')), state: {
    NSW: fin(A('NSW')), Vic: fin(A('VIC')), Qld: fin(A('QLD')), SA: fin(A('SA')), WA: fin(A('WA')),
    'ACT/NT/Tas': fin(sum('ACT','NT','TAS')), 'Non-NSW/Vic/Qld': fin(sum('SA','WA','TAS','ACT','NT')) } };
  const noCls = d.divs.filter(v => !CLS[v.cls]);
  if (y === 1993) { if (noCls.length !== d.divs.length) console.log('1993: some divisions have cls', noCls.length); }
  else {
    if (noCls.length) console.log(`${y}: ${noCls.length} divisions lack cls: ${noCls.map(v=>v.n).join(', ')}`);
    const loc = {}; Object.values(CLS).forEach(k => loc[k] = zero());
    for (const v of d.divs) if (CLS[v.cls]) for (const c of v.c) loc[CLS[v.cls]][BUCKET[c[3]]] += c[4];
    e.location = {}; for (const k in loc) e.location[k] = fin(loc[k]);
    const tot = Object.values(loc).reduce(add, zero()), nat = e.Nat.votes;
    const diff = tot.map((x,i)=>x-nat[i]), fm = nat.reduce((a,b)=>a+b,0);
    const worst = Math.max(...diff.map(x=>Math.abs(x)))/fm*100;
    console.log(`${y} location-sum diff ${JSON.stringify(diff)} (max ${worst.toFixed(4)}% of formal)${noCls.length?' [missing cls]':''}`);
    if (worst >= 0.05) fails.push(`${y} location sum mismatch ${worst.toFixed(3)}%`);
  }
  out.elections[y] = e;
  const p = polls['e'+y];
  if (p) console.log(`${y} Nat v polls.json: ` + ['alp','lnp','onp','grn','oth'].filter(k=>p[k]!=null).map(k=>`${k} ${(e.Nat.pct[KEYS.indexOf(k)]-p[k]).toFixed(2)}`).join('  '));
}
const E = {Nat:[34.56,31.82,6.4,12.2,15.01],NSW:[35.2,31.53,6.02,11.06,16.19],Vic:[33.95,32.2,5.79,13.59,14.48],Qld:[30.98,34.91,7.84,11.76,14.5],SA:[38.31,28.45,6.15,13.42,13.68],WA:[35.59,31.55,7.61,11.97,13.28],'ACT/NT/Tas':[40.95,24.52,3.97,12.49,18.07],'Non-NSW/Vic/Qld':[37.64,29.01,6.34,12.55,14.45],'Inner metro':[38.35,27.98,3.49,16.5,13.68],'Outer metro':[39.28,30.21,6.18,11.87,12.45],Provincial:[35.2,32.6,8.01,11.22,12.97],Rural:[24.41,37.68,8.94,8.41,20.56]};
const e25 = out.elections[2025];
for (const k in E) {
  const got = (k==='Nat'?e25.Nat:e25.state[k]||e25.location[k]).pct;
  const mx = Math.max(...got.map((x,i)=>Math.abs(x-E[k][i])));
  console.log(`2025 ${k}: max diff ${mx.toFixed(2)}${mx>0.1?'  (differs from the site row; gen-data uses the site row) '+got:''}`);
  if (mx > 0.3) fails.push('2025 '+k);
}
fs.writeFileSync(path.join(root,'data/group-counts.json'), JSON.stringify(out,null,1)+'\n');
console.log('Rural / Qld pct (alp lnp onp grn oth)');
for (const y of YEARS) { const e=out.elections[y]; console.log(y, 'Rural', e.location?e.location.Rural.pct.join(' '):'-', '| Qld', e.state.Qld.pct.join(' ')); }
if (fails.length) { console.error('FAILED:', fails.join('; ')); process.exit(1); }
