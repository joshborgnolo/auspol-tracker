/* build-undecided-history.mjs – the past terms' undecided lines for the
   Decidedness panel's window.

   Reads data/undecided-history.json (each past national poll's printed
   undecided share and what it measures: "first", can't say with no leaner
   asked; "leaner", still undecided after a leaner) and fits each term and
   basis with the same model as the current term (primary-model.mjs
   fitUndecided: each pollster's lean drifts, the term's regular pollsters
   average zero, each counting once). A pollster's method eras are separate
   leans (Newspoll by phone and online are different questions about
   different samples). Writes data/undecided-history-model.json, stamped with
   a hash of its input so test-undecided-history.mjs can tell it is current.

   Run after any change to data/undecided-history.json:
     node .build/build-undecided-history.mjs */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { fitUndecided } from "./newtracker/primary-model.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const rd = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, "data", f), "utf8"));
const day = (iso) => Math.floor(Date.parse(iso.slice(0, 10) + "T00:00:00Z") / 864e5);
const iso = (d) => new Date(d * 864e5).toISOString().slice(0, 10);
const r1 = (v) => Math.round(v * 10) / 10;
const DEFF = 1.6;

export function buildUndecidedHistory() {
  const src = fs.readFileSync(path.join(ROOT, "data", "undecided-history.json"), "utf8");
  const W = JSON.parse(src), E = rd("polls.json").elections;
  const elections = Object.values(E).filter((e) => e.date).map((e) => e.date).sort();
  /* past terms only: the sitting term is gen-data's own fit */
  const terms = [];
  for (let i = 1; i < elections.length; i++) terms.push({ from: elections[i - 1], to: elections[i], year: +elections[i].slice(0, 4) });
  const out = [];
  for (const T of terms) {
    const t0 = day(T.from), t1 = day(T.to);
    const months = [];
    for (let d = new Date(T.from.slice(0, 7) + "-01T00:00:00Z"); ; d.setUTCMonth(d.getUTCMonth() + 1)) {
      const ym = d.toISOString().slice(0, 7), mid = Math.min(day(ym + "-15"), t1);
      if (day(ym + "-01") > t1) break;
      if (mid > t0) months.push({ ym, day: mid });
    }
    const series = {};
    for (const basis of ["first", "leaner"]) {
      const rs = W.waves.filter((w) => w.basis === basis && w.und != null && w.end > T.from && w.end < T.to).map((w, idx) => {
        const s = day(w.start || w.end), e = day(w.end);
        return { house: w.house + (w.era ? " · " + w.era : ""), firm: w.house, day: Math.round((s + e) / 2), n: (w.n ? Math.min(w.n, 3000) : 1200) / DEFF * (w.rolling2wk ? 0.5 : 1), und: w.und, idx };
      }).sort((a, b) => a.day - b.day);
      if (rs.length < 4) continue;
      /* the line runs from the month of the term's first such poll to the
         month of its last: no reading carried into years nobody asked */
      const a = rs[0].day, b = rs[rs.length - 1].day;
      const ms = months.filter((m) => m.day >= a - 15 && m.day <= b + 15);
      const fit = fitUndecided(rs, { t0, t1, months: ms, nDraw: 1000, M: 8, seed: 20261128 + T.year + (basis === "first" ? 0 : 1) });
      if (!fit) continue;
      series[basis] = {
        months: fit.months.map((m) => [m.ym, r1(m.v), r1(m.lo), r1(m.hi)]),
        houses: [...new Set(rs.map((r) => r.firm))], zero: fit.core, n: fit.n,
        leans: Object.fromEntries(Object.entries(fit.leans).map(([h, l]) => [h, r1(l.v)])),
      };
    }
    if (Object.keys(series).length) out.push({ year: T.year, from: T.from, to: T.to, series });
  }
  return {
    _about: "Generated by .build/build-undecided-history.mjs from data/undecided-history.json – do not edit. Each past term's modelled undecided share on each basis (months: [ym, mean, 95% low, 95% high], percent of all respondents), the pollsters behind it and those that set its zero.",
    input: createHash("sha1").update(src).digest("hex").slice(0, 12), terms: out,
  };
}
if (process.argv[1] && path.basename(process.argv[1]) === "build-undecided-history.mjs") {
  const m = buildUndecidedHistory();
  fs.writeFileSync(path.join(ROOT, "data", "undecided-history-model.json"), JSON.stringify(m, null, 1) + "\n");
  console.log(`undecided history: ${m.terms.length} terms → data/undecided-history-model.json (input ${m.input})`);
  for (const t of m.terms) console.log(" ", t.year, Object.entries(t.series).map(([b, s]) => `${b} ${s.n} polls (${s.houses.join(", ")}) ${s.months[0][1]}→${s.months[s.months.length - 1][1]}`).join(" | "));
}
